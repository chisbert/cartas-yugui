/**
 * Traduce el nombre de la carta al español si existe en el diccionario oficial,
 * o aplica reglas gramaticales para aproximación.
 */
export function getSpanishCardName(englishName: string): string {
  if (!englishName) return '';
  if (SPANISH_CARD_NAMES[englishName]) {
    return SPANISH_CARD_NAMES[englishName];
  }

  // Traducción inteligente de sufijos y términos comunes en nombres
  let translated = englishName;
  const replacements: Array<[RegExp, string]> = [
    [/\bBlue-Eyes\b/g, 'Ojos Azules'],
    [/\bRed-Eyes\b/g, 'Ojos Rojos'],
    [/\bWhite Dragon\b/g, 'Dragón Blanco'],
    [/\bBlack Dragon\b/g, 'Dragón Negro'],
    [/\bDark Magician\b/g, 'Mago Oscuro'],
    [/\bDragon\b/g, 'Dragón'],
    [/\bDragons\b/g, 'Dragones'],
    [/\bKnight\b/g, 'Caballero'],
    [/\bWarrior\b/g, 'Guerrero'],
    [/\bWarriors\b/g, 'Guerreros'],
    [/\bMagician\b/g, 'Mago'],
    [/\bWitch\b/g, 'Bruja'],
    [/\bLord\b/g, 'Señor'],
    [/\bKing\b/g, 'Rey'],
    [/\bQueen\b/g, 'Reina'],
    [/\bPrincess\b/g, 'Princesa'],
    [/\bSoldier\b/g, 'Soldado'],
    [/\bSword\b/g, 'Espada'],
    [/\bSwordsman\b/g, 'Espadachín'],
    [/\bShield\b/g, 'Escudo'],
    [/\bMirror\b/g, 'Espejo'],
    [/\bForce\b/g, 'Fuerza'],
    [/\bFlame\b/g, 'Llama'],
    [/\bFire\b/g, 'Fuego'],
    [/\bWater\b/g, 'Agua'],
    [/\bThunder\b/g, 'Trueno'],
    [/\bLightning\b/g, 'Relámpago'],
    [/\bChaos\b/g, 'Caos'],
    [/\bShadow\b/g, 'Sombra'],
    [/\bGuardian\b/g, 'Guardián'],
    [/\bDestruction\b/g, 'Destrucción'],
    [/\bCastle\b/g, 'Castillo'],
    [/\bForest\b/g, 'Bosque'],
  ];

  for (const [regex, replacement] of replacements) {
    translated = translated.replace(regex, replacement);
  }

  return translated;
}

